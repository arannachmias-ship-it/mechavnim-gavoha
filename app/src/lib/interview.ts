/** ההיסטוריה בפורמט של ה-API */
export function toApiMessages(msgs: InterviewMsg[]): { role: "user" | "assistant"; content: string }[] {
  const out = msgs.map((m) => ({ role: m.role, content: m.text }));
  if (!out.length || out[0].role !== "user") out.unshift({ role: "user", content: OPENING_USER });
  return out;
}

/** תמלול לטקסט (להורדה) */
export function transcriptText(title: string, msgs: InterviewMsg[], summary?: string | null): string {
  const lines = [`# ${title}`, ""];
  for (const m of msgs) lines.push(`**${m.role === "assistant" ? "המראיינת" : "נגה"}:** ${m.text}`, "");
  if (summary) lines.push("---", "", "## ממצאים", "", summary);
  return lines.join("\n");
}
