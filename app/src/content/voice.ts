/** מחזור בלי חזרות בתוך ישיבה */
export class Rotator {
  private used = new Map<string, number[]>();
  pick<T>(key: string, arr: readonly T[]): T {
    let u = this.used.get(key);
    if (!u || u.length >= arr.length) {
      u = [];
      this.used.set(key, u);
    }
    const free = arr.map((_, i) => i).filter((i) => !u!.includes(i));
    const i = free[Math.floor(Math.random() * free.length)];
    u.push(i);
    return arr[i];
  }
}

